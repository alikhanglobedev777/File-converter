const { randomBytes, randomInt, createHash, createHmac } = require('node:crypto');
const bcrypt = require('bcryptjs');
const User = require('../model/user');
const mail = require('../services/password-reset-mail');

const RESET_LIFETIME_MS = 10 * 60 * 1000;
const RESET_COOLDOWN_MS = 60 * 1000;
const VERIFIED_LIFETIME_MS = 5 * 60 * 1000;
const MAX_CODE_ATTEMPTS = 5;
const GENERIC_RESPONSE = 'If that email is registered, a six-digit verification code will be sent shortly.';
const BAD_CODE_RESPONSE = 'The code is incorrect, expired, or has reached its attempt limit. Request a new code.';

function normalizedEmail(value) {
  if (typeof value !== 'string') return null;
  const result = value.trim().toLowerCase();
  return result.length <= 254 && /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(result) ? result : null;
}
function hashToken(token) {
  return createHash('sha256').update(token).digest('hex');
}
function hashCode(email, code, secret = process.env.JWT_SECRET) {
  // Unlike an ordinary SHA-256 digest of a six-digit value, keyed HMAC
  // prevents offline code enumeration if the user database is exposed.
  if (!secret || secret.length < 32) throw new Error('JWT_SECRET is not configured');
  return createHmac('sha256', secret).update(email + ':' + code).digest('hex');
}
function newSixDigitCode() {
  return randomInt(0, 1000000).toString().padStart(6, '0');
}

function createPasswordResetHandlers({
  UserModel = User,
  emailReady = () => !!mail.emailJsConfig(),
  sendEmail = mail.sendPasswordResetEmail,
  clock = () => Date.now(),
  logger = console,
  hashCodeForUser = hashCode,
} = {}) {
  const forgotPassword = async (req, res) => {
    const email = normalizedEmail(req.body?.email);
    if (!email) return res.status(400).json({ error: 'Enter a valid email address.' });
    try {
      // Never reveal whether a user is registered, including when mail fails.
      const user = await UserModel.findOne({ email }).select('+passwordResetRequestedAt');
      if (!user) return res.json({ message: GENERIC_RESPONSE });
      if (!emailReady()) {
        logger.error('Password reset email service is not configured');
        return res.json({ message: GENERIC_RESPONSE });
      }
      const now = clock();
      if (user.passwordResetRequestedAt &&
          now - new Date(user.passwordResetRequestedAt).getTime() < RESET_COOLDOWN_MS) {
        return res.json({ message: GENERIC_RESPONSE });
      }
      const code = newSixDigitCode();
      const codeHash = hashCodeForUser(email, code);
      // Atomic per-account cooldown prevents concurrent reset-email floods.
      const updated = await UserModel.updateOne({
        _id: user._id,
        $or: [
          { passwordResetRequestedAt: { $exists: false } },
          { passwordResetRequestedAt: { $lte: new Date(now - RESET_COOLDOWN_MS) } },
        ],
      }, {
        $set: {
          passwordResetCodeHash: codeHash,
          passwordResetExpiresAt: new Date(now + RESET_LIFETIME_MS),
          passwordResetRequestedAt: new Date(now),
          passwordResetAttempts: 0,
        },
        $unset: {
          passwordResetTokenHash: 1,
          passwordResetVerifiedTokenHash: 1,
          passwordResetVerifiedExpiresAt: 1,
        },
      });
      if (!updated.matchedCount) return res.json({ message: GENERIC_RESPONSE });
      try {
        await sendEmail({ toEmail: user.email, toName: user.name, code });
      } catch (error) {
        // Only cancel the code generated by this request, not a newer code.
        await UserModel.updateOne({ _id: user._id, passwordResetCodeHash: codeHash }, {
          $unset: {
            passwordResetCodeHash: 1,
            passwordResetExpiresAt: 1,
            passwordResetRequestedAt: 1,
            passwordResetAttempts: 1,
          },
        }).catch(() => {});
        logger.error('Password reset email delivery failed', {
          status: error?.status, name: error?.name,
        });
      }
      return res.json({ message: GENERIC_RESPONSE });
    } catch (error) {
      logger.error('Password reset request failed', { name: error?.name });
      return res.status(503).json({ error: 'Password recovery is temporarily unavailable.' });
    }
  };

  const verifyResetCode = async (req, res) => {
    const email = normalizedEmail(req.body?.email);
    const code = req.body?.code;
    if (!email || typeof code !== 'string' || !/^[0-9]{6}$/.test(code)) {
      return res.status(400).json({ error: BAD_CODE_RESPONSE });
    }
    try {
      const now = clock();
      // The code comparison and consumption happen atomically in MongoDB.
      // Even if guesses arrive simultaneously, at most five attempts can
      // be processed and a correct code produces one verification grant.
      const grant = randomBytes(32).toString('hex');
      const result = await UserModel.updateOne({
        email,
        passwordResetCodeHash: hashCodeForUser(email, code),
        passwordResetExpiresAt: { $gt: new Date(now) },
        passwordResetAttempts: { $lt: MAX_CODE_ATTEMPTS },
      }, {
        $set: {
          passwordResetVerifiedTokenHash: hashToken(grant),
          passwordResetVerifiedExpiresAt: new Date(now + VERIFIED_LIFETIME_MS),
        },
        $unset: { passwordResetCodeHash: 1, passwordResetExpiresAt: 1,
          passwordResetAttempts: 1 },
      });
      if (result.matchedCount) {
        return res.json({ resetToken: grant, expiresInSeconds: VERIFIED_LIFETIME_MS / 1000 });
      }
      // Penalize wrong guesses durably (even after server restarts).
      await UserModel.updateOne({
        email,
        passwordResetCodeHash: { $exists: true },
        passwordResetExpiresAt: { $gt: new Date(now) },
        passwordResetAttempts: { $lt: MAX_CODE_ATTEMPTS },
      }, { $inc: { passwordResetAttempts: 1 } });
      return res.status(400).json({ error: BAD_CODE_RESPONSE });
    } catch (error) {
      logger.error('Password reset code verification failed', { name: error?.name });
      return res.status(503).json({ error: 'Password recovery is temporarily unavailable.' });
    }
  };

  const resetPassword = async (req, res) => {
    const { resetToken, password } = req.body || {};
    if (typeof resetToken !== 'string' || !/^[0-9a-f]{64}$/i.test(resetToken)) {
      return res.status(400).json({ error: 'Verification expired. Request a new code.' });
    }
    if (typeof password !== 'string' || password.length < 8 || password.length > 128) {
      return res.status(400).json({ error: 'Password must contain 8 to 128 characters.' });
    }
    try {
      const hashedPassword = await bcrypt.hash(password, 12);
      const result = await UserModel.updateOne({
        passwordResetVerifiedTokenHash: hashToken(resetToken),
        passwordResetVerifiedExpiresAt: { $gt: new Date(clock()) },
      }, {
        $set: { password: hashedPassword },
        $unset: {
          passwordResetVerifiedTokenHash: 1,
          passwordResetVerifiedExpiresAt: 1,
          passwordResetCodeHash: 1,
          passwordResetExpiresAt: 1,
          passwordResetRequestedAt: 1,
          passwordResetAttempts: 1,
          passwordResetTokenHash: 1,
        },
        $inc: { tokenVersion: 1 },
      });
      if (!result.matchedCount) {
        return res.status(400).json({ error: 'Verification expired. Request a new code.' });
      }
      return res.json({ message: 'Your password was reset. Please log in.' });
    } catch (error) {
      logger.error('Password reset failed', { name: error?.name });
      return res.status(503).json({ error: 'Password recovery is temporarily unavailable.' });
    }
  };

  return { forgotPassword, verifyResetCode, resetPassword };
}

module.exports = {
  ...createPasswordResetHandlers(), createPasswordResetHandlers,
  normalizedEmail, hashToken, hashCode, newSixDigitCode,
  RESET_LIFETIME_MS, RESET_COOLDOWN_MS, VERIFIED_LIFETIME_MS,
  MAX_CODE_ATTEMPTS, GENERIC_RESPONSE, BAD_CODE_RESPONSE,
};
